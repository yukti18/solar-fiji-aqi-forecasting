def find_pm25_variable(
    dataset,
):

    preferred_names = [

        "pm2p5",

        "pm2_5",

        "pm25",

        "PM2P5",

        "PM25",

        (
            "particulate_matter_"
            "2.5um"
        ),

        (
            "mass_concentration_of_"
            "pm2p5_ambient_aerosol_"
            "particles_in_air"
        ),
    ]


    for preferred_name in preferred_names:

        if preferred_name in dataset.data_vars:

            return preferred_name


    lower_name_mapping = {

        variable.lower():
            variable

        for variable
        in dataset.data_vars
    }


    for preferred_name in preferred_names:

        if (
            preferred_name.lower()
            in lower_name_mapping
        ):

            return lower_name_mapping[
                preferred_name.lower()
            ]


    for variable in dataset.data_vars:

        cleaned_name = (

            variable

            .lower()

            .replace("_", "")

            .replace(".", "")
        )


        if (

            "pm25"
            in cleaned_name

            or

            "pm2p5"
            in cleaned_name

        ):

            return variable


    raise ValueError(

        "Could not automatically find "
        "the PM2.5 variable."
    )

def find_time_coordinate(
    dataset,
):

    preferred_names = [

        "time",

        "valid_time",

        "datetime",

        "date",
    ]


    for name in preferred_names:

        if name in dataset.coords:

            return name


    for name in preferred_names:

        if name in dataset.dims:

            return name


    raise ValueError(

        "Could not identify a time coordinate."
    )


def convert_pm25_to_micrograms(
    values,
    units,
):

    values = np.asarray(
        values,
        dtype=float,
    )


    units_text = str(
        units
    ).lower()


    # kg/m³ -> µg/m³
    if (

        "kg"
        in units_text

        and

        (
            "m-3"
            in units_text

            or

            "m**-3"
            in units_text

            or

            "m3"
            in units_text
        )

    ):

        return (
            values
            * 1_000_000_000
        )

    if (

        "ug"
        in units_text

        or

        "µg"
        in units_text

        or

        "microgram"
        in units_text

    ):

        return values


    finite_values = values[
        np.isfinite(values)
    ]


    if len(finite_values) == 0:

        return values


    median_value = np.nanmedian(
        np.abs(
            finite_values
        )
    )

    if median_value < 0.001:

        print(
            "Unit inference: converting "
            "PM2.5 from kg/m³ to µg/m³."
        )

        return (
            values
            * 1_000_000_000
        )


    print(
        "Unit inference: PM2.5 appears "
        "already expressed in µg/m³."
    )

    return values

