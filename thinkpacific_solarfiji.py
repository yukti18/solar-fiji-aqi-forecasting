def calculate_smape(
    actual,
    predicted,
):

    actual = np.asarray(
        actual,
        dtype=float,
    )

    predicted = np.asarray(
        predicted,
        dtype=float,
    )


    denominator = (

        np.abs(actual)

        +

        np.abs(predicted)

        +

        1e-8
    )


    return float(

        np.mean(

            2

            * np.abs(
                predicted - actual
            )

            / denominator

        )

        * 100
    )


def calculate_metrics(
    actual,
    predicted,
):

    actual = np.asarray(
        actual,
        dtype=float,
    )

    predicted = np.asarray(
        predicted,
        dtype=float,
    )


    return {

        "MAE":

            float(

                mean_absolute_error(
                    actual,
                    predicted,
                )
            ),


        "RMSE":

            float(

                np.sqrt(

                    mean_squared_error(
                        actual,
                        predicted,
                    )
                )
            ),


        "R2":

            float(

                r2_score(
                    actual,
                    predicted,
                )
            ),


        "sMAPE_percent":

            calculate_smape(
                actual,
                predicted,
            ),

    }

