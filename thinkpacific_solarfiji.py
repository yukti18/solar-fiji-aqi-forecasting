def download_historical_weather_chunk(
    start_date,
    end_date,
    max_retries=5,
):
    """
    Download one period of hourly historical GFS
    forecast-model weather data.
    """

    parameters = {

        "latitude":
            LATITUDE,

        "longitude":
            LONGITUDE,

        "start_date":
            start_date.strftime(
                "%Y-%m-%d"
            ),

        "end_date":
            end_date.strftime(
                "%Y-%m-%d"
            ),

        "hourly":
            ",".join(
                HOURLY_WEATHER_VARIABLES
            ),

        "models":
            WEATHER_MODEL,

        "timezone":
            TIMEZONE,

        "wind_speed_unit":
            "ms",

        "temperature_unit":
            "celsius",

        "precipitation_unit":
            "mm",
    }


    for attempt in range(
        1,
        max_retries + 1,
    ):

        try:

            response = requests.get(
                HISTORICAL_WEATHER_URL,
                params=parameters,
                timeout=180,
            )


            if response.status_code == 200:

                data = response.json()

                if "hourly" not in data:
                    raise ValueError(
                        "No hourly data returned."
                    )


                dataframe = pd.DataFrame(
                    data["hourly"]
                )


                dataframe["time"] = (
                    pd.to_datetime(
                        dataframe["time"]
                    )
                )


                return dataframe


            print(
                f"Attempt {attempt}: "
                f"HTTP {response.status_code}"
            )

            print(
                response.text[:500]
            )


        except Exception as error:

            print(
                f"Attempt {attempt} failed:"
            )

            print(error)


        if attempt < max_retries:

            wait_seconds = (
                attempt * 5
            )

            print(
                f"Waiting "
                f"{wait_seconds} seconds..."
            )

            time.sleep(
                wait_seconds
            )


    raise RuntimeError(
        f"""
Unable to download historical weather:

{start_date.date()}
to
{end_date.date()}
"""
    )

