def calculate_solar_impact(
    aqi_category,
    radiation,
    rainfall,
):

    score = {

        "Good":
            1,

        "Moderate":
            2,

        (
            "Unhealthy for "
            "Sensitive Groups"
        ):
            3,

        "Unhealthy":
            4,

        "Very Unhealthy":
            5,

        "Hazardous":
            5,

        "Unknown":
            2,

    }.get(
        aqi_category,
        2,
    )


    if not pd.isna(
        radiation
    ):

        if radiation < 2:

            score += 2

        elif radiation < 4:

            score += 1


    if (

        not pd.isna(
            rainfall
        )

        and

        rainfall >= 10

    ):

        score -= 1


    if score <= 1:

        return "Low"


    elif score <= 3:

        return "Moderate"


    else:

        return "Higher"


