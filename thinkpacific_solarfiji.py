def fit_and_walk_forward_arimax(

    order,

    training_target,

    training_exog,

    evaluation_target,

    evaluation_exog,

):

    training_target = np.asarray(
        training_target,
        dtype=np.float64,
    )


    training_exog = np.asarray(
        training_exog,
        dtype=np.float64,
    )


    evaluation_target = np.asarray(
        evaluation_target,
        dtype=np.float64,
    )


    evaluation_exog = np.asarray(
        evaluation_exog,
        dtype=np.float64,
    )


    model = SARIMAX(

        endog=training_target,

        exog=training_exog,

        order=order,

        trend="c",

        enforce_stationarity=False,

        enforce_invertibility=False,
    )


    fitted_results = model.fit(

        disp=False,

        maxiter=500,
    )


    current_results = (
        fitted_results
    )


    predictions = []

    lower_intervals = []

    upper_intervals = []

    for position in range(

        len(
            evaluation_target
        )

    ):


        next_exog = (

            evaluation_exog[

                position:
                position + 1

            ]

        )

        forecast_result = (

            current_results

            .get_forecast(

                steps=1,

                exog=next_exog,
            )
        )


        prediction = float(

            np.asarray(

                forecast_result
                .predicted_mean

            )

            .reshape(-1)[0]
        )


        confidence_interval = (

            np.asarray(

                forecast_result

                .conf_int(
                    alpha=0.05
                )

            )

            .reshape(
                -1,
                2,
            )[0]
        )


        predictions.append(
            prediction
        )


        lower_intervals.append(

            float(
                confidence_interval[0]
            )
        )


        upper_intervals.append(

            float(
                confidence_interval[1]
            )
        )

        new_endog = np.asarray(

            [

                evaluation_target[
                    position
                ]

            ],

            dtype=np.float64,
        )


        current_results = (

            current_results

            .append(

                endog=new_endog,

                exog=next_exog,

                refit=False,
            )
        )


    return (

        fitted_results,

        current_results,

        np.asarray(
            predictions,
            dtype=float,
        ),

        np.asarray(
            lower_intervals,
            dtype=float,
        ),

        np.asarray(
            upper_intervals,
            dtype=float,
        ),

    )

