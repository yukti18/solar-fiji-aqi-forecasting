def circular_mean_degrees(
    values,
):

    values = pd.Series(
        values
    ).dropna()


    if values.empty:

        return np.nan


    radians = np.deg2rad(

        values.astype(float)
    )


    mean_sin = np.mean(

        np.sin(
            radians
        )
    )


    mean_cos = np.mean(

        np.cos(
            radians
        )
    )


    angle = np.rad2deg(

        np.arctan2(

            mean_sin,

            mean_cos,
        )
    )


    return float(
        angle % 360
    )

