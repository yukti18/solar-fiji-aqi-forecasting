def calculate_pm25_aqi(pm25):

    if pd.isna(pm25):
        return np.nan

    pm25 = max(
        0.0,
        float(pm25),
    )

    pm25 = np.floor(
        pm25 * 10
    ) / 10

    breakpoints = [
        (0.0, 9.0, 0, 50),
        (9.1, 35.4, 51, 100),
        (35.5, 55.4, 101, 150),
        (55.5, 125.4, 151, 200),
        (125.5, 225.4, 201, 300),
        (225.5, 325.4, 301, 500),
    ]

    for (
        concentration_low,
        concentration_high,
        aqi_low,
        aqi_high,
    ) in breakpoints:

        if (
            concentration_low
            <= pm25
            <= concentration_high
        ):

            aqi = (
                (
                    aqi_high
                    - aqi_low
                )
                /
                (
                    concentration_high
                    - concentration_low
                )
                *
                (
                    pm25
                    - concentration_low
                )
                +
                aqi_low
            )

            return int(round(aqi))

    return 500


def assign_aqi_category(aqi):

    if pd.isna(aqi):
        return "Unknown"

    if aqi <= 50:
        return "Good"

    elif aqi <= 100:
        return "Moderate"

    elif aqi <= 150:
        return (
            "Unhealthy for Sensitive Groups"
        )

    elif aqi <= 200:
        return "Unhealthy"

    elif aqi <= 300:
        return "Very Unhealthy"

    else:
        return "Hazardous"


