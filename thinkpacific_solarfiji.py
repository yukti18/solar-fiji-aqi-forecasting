def calculate_smape(
    actual,
    predicted,
):

    actual = np.asarray(
        actual,
        dtype=float,
    )

    predicted = np.asarray(
        predicted,
        dtype=float,
    )

    denominator = (
        np.abs(actual)
        + np.abs(predicted)
        + 1e-8
    )

    return float(

        np.mean(

            2
            * np.abs(
                predicted - actual
            )
            / denominator

        )
        * 100
    )


def calculate_metrics(
    actual,
    predicted,
):

    actual = np.asarray(
        actual,
        dtype=float,
    )

    predicted = np.asarray(
        predicted,
        dtype=float,
    )

    return {

        "MAE":
            float(
                mean_absolute_error(
                    actual,
                    predicted,
                )
            ),

        "RMSE":
            float(
                np.sqrt(
                    mean_squared_error(
                        actual,
                        predicted,
                    )
                )
            ),

        "R2":
            float(
                r2_score(
                    actual,
                    predicted,
                )
            ),

        "sMAPE_percent":
            calculate_smape(
                actual,
                predicted,
            ),
    }

def calculate_pm25_aqi(pm25):

    if pd.isna(pm25):
        return np.nan

    pm25 = max(
        0.0,
        float(pm25),
    )

    pm25 = (
        np.floor(pm25 * 10)
        / 10
    )

    breakpoints = [

        (0.0, 9.0, 0, 50),

        (9.1, 35.4, 51, 100),

        (35.5, 55.4, 101, 150),

        (55.5, 125.4, 151, 200),

        (125.5, 225.4, 201, 300),

        (225.5, 325.4, 301, 500),
    ]


    for (
        concentration_low,
        concentration_high,
        aqi_low,
        aqi_high,
    ) in breakpoints:

        if (
            concentration_low
            <= pm25
            <= concentration_high
        ):

            aqi = (

                (
                    aqi_high
                    - aqi_low
                )

                /

                (
                    concentration_high
                    - concentration_low
                )

                *

                (
                    pm25
                    - concentration_low
                )

                +

                aqi_low
            )

            return int(
                round(aqi)
            )

    return 500


def assign_aqi_category(aqi):

    if pd.isna(aqi):
        return "Unknown"

    if aqi <= 50:
        return "Good"

    elif aqi <= 100:
        return "Moderate"

    elif aqi <= 150:
        return (
            "Unhealthy for Sensitive Groups"
        )

    elif aqi <= 200:
        return "Unhealthy"

    elif aqi <= 300:
        return "Very Unhealthy"

    else:
        return "Hazardous"


def calculate_aqi_metrics(
    actual_pm25,
    predicted_pm25,
):

    actual_categories = np.asarray([

        assign_aqi_category(
            calculate_pm25_aqi(value)
        )

        for value
        in actual_pm25

    ])


    predicted_categories = np.asarray([

        assign_aqi_category(
            calculate_pm25_aqi(value)
        )

        for value
        in predicted_pm25

    ])


    actual_moderate = (
        actual_categories
        == "Moderate"
    )

    predicted_moderate = (
        predicted_categories
        == "Moderate"
    )


    return {

        "AQI_accuracy":
            float(
                accuracy_score(
                    actual_categories,
                    predicted_categories,
                )
            ),

        "AQI_macro_F1":
            float(
                f1_score(
                    actual_categories,
                    predicted_categories,
                    average="macro",
                    zero_division=0,
                )
            ),

        "AQI_weighted_F1":
            float(
                f1_score(
                    actual_categories,
                    predicted_categories,
                    average="weighted",
                    zero_division=0,
                )
            ),

        "Moderate_recall":
            float(
                recall_score(
                    actual_moderate,
                    predicted_moderate,
                    zero_division=0,
                )
            ),
    }


